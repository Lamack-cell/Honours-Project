def verify_stored_daily_metrics(
    recalculated_daily: pd.DataFrame,
    stored_daily: pd.DataFrame,
    model_prefix: str,
    model_name: str,
) -> dict[str, object]:
    """
    Confirm that Script 09 reproduces the daily metrics stored
    by Scripts 07 and 08.

    A tolerance of 1e-8 is used for CSV round-trip floating-point
    comparisons.
    """

    stored_subset = stored_daily[
        [
            "Date",
            "Outer_Window_ID",
            "Test_Quarter",
            "Model_Eligible_Securities",
            "Daily_IC",
            "Daily_MAE",
            "Daily_RMSE",
            "Top_Quartile_Hit_Rate",
            "Bottom_Quartile_Hit_Rate",
        ]
    ].rename(
        columns={
            "Model_Eligible_Securities": (
                f"{model_prefix}_Stored_N"
            ),
            "Daily_IC": (
                f"{model_prefix}_Stored_IC"
            ),
            "Daily_MAE": (
                f"{model_prefix}_Stored_MAE"
            ),
            "Daily_RMSE": (
                f"{model_prefix}_Stored_RMSE"
            ),
            "Top_Quartile_Hit_Rate": (
                f"{model_prefix}_Stored_Top"
            ),
            "Bottom_Quartile_Hit_Rate": (
                f"{model_prefix}_Stored_Bottom"
            ),
        }
    )

    comparison = recalculated_daily.merge(
        stored_subset,
        on=[
            "Date",
            "Outer_Window_ID",
            "Test_Quarter",
        ],
        how="outer",
        indicator=True,
        validate="one_to_one",
    )

    unmatched_dates = int(
        comparison[
            "_merge"
        ].ne(
            "both"
        ).sum()
    )

    if unmatched_dates > 0:
        raise AssertionError(
            f"{model_name} stored and recalculated daily dates "
            "do not match."
        )

    column_pairs = {
        "IC": (
            f"{model_prefix}_Daily_IC",
            f"{model_prefix}_Stored_IC",
        ),
        "MAE": (
            f"{model_prefix}_Daily_MAE",
            f"{model_prefix}_Stored_MAE",
        ),
        "RMSE": (
            f"{model_prefix}_Daily_RMSE",
            f"{model_prefix}_Stored_RMSE",
        ),
        "Top_Hit_Rate": (
            f"{model_prefix}_Top_Quartile_Hit_Rate",
            f"{model_prefix}_Stored_Top",
        ),
        "Bottom_Hit_Rate": (
            f"{model_prefix}_Bottom_Quartile_Hit_Rate",
            f"{model_prefix}_Stored_Bottom",
        ),
    }

    maximum_differences: dict[
        str,
        float,
    ] = {}

    for metric_name, (
        recalculated_column,
        stored_column,
    ) in column_pairs.items():
        differences = np.abs(
            comparison[
                recalculated_column
            ].to_numpy(
                dtype=float
            )
            - comparison[
                stored_column
            ].to_numpy(
                dtype=float
            )
        )

        maximum_difference = float(
            np.max(
                differences
            )
        )

        maximum_differences[
            metric_name
        ] = maximum_difference

        if (
            maximum_difference
            > STORED_METRIC_TOLERANCE
        ):
            raise AssertionError(
                f"{model_name} recalculated {metric_name} differs "
                f"from stored output by "
                f"{maximum_difference:.3e}, which exceeds the "
                f"{STORED_METRIC_TOLERANCE:.1e} tolerance."
            )

    cross_section_size_mismatches = int(
        comparison[
            "Model_Eligible_Securities"
        ].astype(
            int
        ).ne(
            comparison[
                f"{model_prefix}_Stored_N"
            ].astype(
                int
            )
        ).sum()
    )

    if cross_section_size_mismatches > 0:
        raise AssertionError(
            f"{model_name} stored cross-sectional sizes "
            "do not match the recalculated values."
        )

    return {
        "Model": model_name,
        "Stored_Metric_Check": "Passed",
        "Unmatched_Dates": unmatched_dates,
        "Cross_Section_Size_Mismatches": (
            cross_section_size_mismatches
        ),
        "Maximum_Absolute_IC_Difference": (
            maximum_differences[
                "IC"
            ]
        ),
        "Maximum_Absolute_MAE_Difference": (
            maximum_differences[
                "MAE"
            ]
        ),
        "Maximum_Absolute_RMSE_Difference": (
            maximum_differences[
                "RMSE"
            ]
        ),
        "Maximum_Absolute_Top_Hit_Difference": (
            maximum_differences[
                "Top_Hit_Rate"
            ]
        ),
        "Maximum_Absolute_Bottom_Hit_Difference": (
            maximum_differences[
                "Bottom_Hit_Rate"
            ]
        ),
        "Metric_Comparison_Tolerance": (
            STORED_METRIC_TOLERANCE
        ),
    }


