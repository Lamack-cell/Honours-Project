def calculate_ic_information_ratio(
    ic_values: pd.Series,
) -> float:
    """Calculate the unannualised IC information ratio."""

    standard_deviation = float(
        ic_values.std(
            ddof=1
        )
    )

    if (
        not np.isfinite(
            standard_deviation
        )
        or standard_deviation <= 0
    ):
        return np.nan

    return float(
        ic_values.mean()
        / standard_deviation
    )


def determine_descriptive_winner(
    ols_value: float,
    xgb_value: float,
    higher_is_better: bool,
) -> str:
    """Determine the descriptive winner for one comparison metric."""

    if np.isclose(
        ols_value,
        xgb_value,
        rtol=0.0,
        atol=STORED_METRIC_TOLERANCE,
    ):
        return "Tie"

    if higher_is_better:
        return (
            "Pooled OLS"
            if ols_value > xgb_value
            else "XGBoost"
        )

    return (
        "Pooled OLS"
        if ols_value < xgb_value
        else "XGBoost"
    )


