def validate_prediction_panel(
    panel: pd.DataFrame,
    model_name: str,
    score_column: str,
    percentile_column: str,
) -> None:
    """Validate one model's out-of-sample prediction panel."""

    required_columns = {
        *MERGE_KEYS,
        *SHARED_MODEL_COLUMNS,
        score_column,
        percentile_column,
    }

    missing_columns = required_columns.difference(
        panel.columns
    )

    if missing_columns:
        raise ValueError(
            f"{model_name} prediction file is missing required columns: "
            f"{sorted(missing_columns)}"
        )

    if panel.empty:
        raise ValueError(
            f"{model_name} prediction file contains no observations."
        )

    duplicate_count = int(
        panel.duplicated(
            [
                "Date",
                "Ticker",
            ]
        ).sum()
    )

    if duplicate_count > 0:
        raise ValueError(
            f"{model_name} prediction file contains "
            f"{duplicate_count:,} duplicate Date-Ticker observations."
        )

    required_nonmissing_columns = [
        *MERGE_KEYS,
        *SHARED_MODEL_COLUMNS,
        score_column,
        percentile_column,
    ]

    missing_values = int(
        panel[
            required_nonmissing_columns
        ]
        .isna()
        .sum()
        .sum()
    )

    if missing_values > 0:
        raise ValueError(
            f"{model_name} prediction file contains "
            f"{missing_values:,} missing required values."
        )

    numerical_columns = [
        *SHARED_MODEL_COLUMNS,
        score_column,
        percentile_column,
    ]

    numerical_values = panel[
        numerical_columns
    ].to_numpy(
        dtype=float
    )

    if not np.isfinite(
        numerical_values
    ).all():
        raise ValueError(
            f"{model_name} prediction file contains non-finite values."
        )

    if not panel[
        "Target_Y"
    ].between(
        0,
        1,
        inclusive="both",
    ).all():
        raise ValueError(
            f"{model_name} Target_Y contains values outside [0, 1]."
        )

    if not panel[
        percentile_column
    ].between(
        0,
        1,
        inclusive="both",
    ).all():
        raise ValueError(
            f"{model_name} predicted percentile contains values "
            "outside [0, 1]."
        )

    if panel[
        "Outer_Window_ID"
    ].nunique() != 9:
        raise ValueError(
            f"{model_name} prediction file does not contain "
            "the expected nine outer windows."
        )


