def safe_spearman_ic(
    predicted_scores: pd.Series,
    realised_target: pd.Series,
) -> float:
    """
    Calculate a safe daily Spearman Information Coefficient.

    Constant prediction or target vectors are assigned an IC of zero
    because they contain no cross-sectional ranking information.
    """

    if len(
        predicted_scores
    ) < MINIMUM_DAILY_CROSS_SECTION:
        return np.nan

    if (
        predicted_scores.nunique(
            dropna=True
        )
        <= 1
    ):
        return 0.0

    if (
        realised_target.nunique(
            dropna=True
        )
        <= 1
    ):
        return 0.0

    result = spearmanr(
        predicted_scores,
        realised_target,
    )

    statistic = float(
        result.statistic
    )

    if not np.isfinite(
        statistic
    ):
        return 0.0

    return statistic


def calculate_quartile_hit_rates(
    group: pd.DataFrame,
    score_column: str,
) -> tuple[float, float, int]:
    """
    Calculate deterministic top- and bottom-quartile overlap.

    Ticker order is used as a deterministic tie-break when model
    predictions are equal.
    """

    number_of_assets = len(
        group
    )

    quartile_size = max(
        1,
        int(
            np.ceil(
                number_of_assets
                * TOP_BOTTOM_FRACTION
            )
        ),
    )

    predicted_order = group.sort_values(
        [
            score_column,
            "Ticker",
        ],
        ascending=[
            False,
            True,
        ],
        kind="mergesort",
    )

    realised_order = group.sort_values(
        [
            "Target_Y",
            "Ticker",
        ],
        ascending=[
            False,
            True,
        ],
        kind="mergesort",
    )

    predicted_top = set(
        predicted_order.head(
            quartile_size
        )[
            "Ticker"
        ]
    )

    predicted_bottom = set(
        predicted_order.tail(
            quartile_size
        )[
            "Ticker"
        ]
    )

    realised_top = set(
        realised_order.head(
            quartile_size
        )[
            "Ticker"
        ]
    )

    realised_bottom = set(
        realised_order.tail(
            quartile_size
        )[
            "Ticker"
        ]
    )

    top_hit_rate = (
        len(
            predicted_top.intersection(
                realised_top
            )
        )
        / quartile_size
    )

    bottom_hit_rate = (
        len(
            predicted_bottom.intersection(
                realised_bottom
            )
        )
        / quartile_size
    )

    return (
        float(
            top_hit_rate
        ),
        float(
            bottom_hit_rate
        ),
        quartile_size,
    )


def calculate_paired_daily_performance(
    paired_predictions: pd.DataFrame,
) -> pd.DataFrame:
    """
    Recalculate OLS and XGBoost performance on the identical
    daily Date-Ticker sample.
    """

    records: list[
        dict[str, object]
    ] = []

    for date, group in paired_predictions.groupby(
        "Date",
        sort=True,
    ):
        ols_daily_ic = safe_spearman_ic(
            predicted_scores=group[
                OLS_SCORE_COLUMN
            ],
            realised_target=group[
                "Target_Y"
            ],
        )

        xgb_daily_ic = safe_spearman_ic(
            predicted_scores=group[
                XGB_SCORE_COLUMN
            ],
            realised_target=group[
                "Target_Y"
            ],
        )

        ols_errors = (
            group[
                OLS_SCORE_COLUMN
            ]
            - group[
                "Target_Y"
            ]
        )

        xgb_errors = (
            group[
                XGB_SCORE_COLUMN
            ]
            - group[
                "Target_Y"
            ]
        )

        (
            ols_top_hit_rate,
            ols_bottom_hit_rate,
            ols_quartile_size,
        ) = calculate_quartile_hit_rates(
            group=group,
            score_column=OLS_SCORE_COLUMN,
        )

        (
            xgb_top_hit_rate,
            xgb_bottom_hit_rate,
            xgb_quartile_size,
        ) = calculate_quartile_hit_rates(
            group=group,
            score_column=XGB_SCORE_COLUMN,
        )

        if (
            ols_quartile_size
            != xgb_quartile_size
        ):
            raise AssertionError(
                "OLS and XGBoost used different quartile sizes "
                f"on {date}."
            )

        records.append(
            {
                "Date": date,
                "Outer_Window_ID": group[
                    "Outer_Window_ID"
                ].iloc[
                    0
                ],
                "Test_Quarter": group[
                    "Test_Quarter"
                ].iloc[
                    0
                ],
                "Model_Eligible_Securities": len(
                    group
                ),
                "Quartile_Size": (
                    ols_quartile_size
                ),
                "OLS_Daily_IC": (
                    ols_daily_ic
                ),
                "XGB_Daily_IC": (
                    xgb_daily_ic
                ),
                "IC_Difference_XGB_Minus_OLS": (
                    xgb_daily_ic
                    - ols_daily_ic
                ),
                "OLS_Daily_MAE": float(
                    np.mean(
                        np.abs(
                            ols_errors
                        )
                    )
                ),
                "XGB_Daily_MAE": float(
                    np.mean(
                        np.abs(
                            xgb_errors
                        )
                    )
                ),
                "OLS_Daily_RMSE": float(
                    np.sqrt(
                        np.mean(
                            ols_errors ** 2
                        )
                    )
                ),
                "XGB_Daily_RMSE": float(
                    np.sqrt(
                        np.mean(
                            xgb_errors ** 2
                        )
                    )
                ),
                "OLS_Top_Quartile_Hit_Rate": (
                    ols_top_hit_rate
                ),
                "XGB_Top_Quartile_Hit_Rate": (
                    xgb_top_hit_rate
                ),
                "OLS_Bottom_Quartile_Hit_Rate": (
                    ols_bottom_hit_rate
                ),
                "XGB_Bottom_Quartile_Hit_Rate": (
                    xgb_bottom_hit_rate
                ),
            }
        )

    daily_performance = (
        pd.DataFrame(
            records
        )
        .sort_values(
            "Date"
        )
        .reset_index(
            drop=True
        )
    )

    daily_performance[
        "MAE_Difference_XGB_Minus_OLS"
    ] = (
        daily_performance[
            "XGB_Daily_MAE"
        ]
        - daily_performance[
            "OLS_Daily_MAE"
        ]
    )

    daily_performance[
        "RMSE_Difference_XGB_Minus_OLS"
    ] = (
        daily_performance[
            "XGB_Daily_RMSE"
        ]
        - daily_performance[
            "OLS_Daily_RMSE"
        ]
    )

    daily_performance[
        "Top_Hit_Difference_XGB_Minus_OLS"
    ] = (
        daily_performance[
            "XGB_Top_Quartile_Hit_Rate"
        ]
        - daily_performance[
            "OLS_Top_Quartile_Hit_Rate"
        ]
    )

    daily_performance[
        "Bottom_Hit_Difference_XGB_Minus_OLS"
    ] = (
        daily_performance[
            "XGB_Bottom_Quartile_Hit_Rate"
        ]
        - daily_performance[
            "OLS_Bottom_Quartile_Hit_Rate"
        ]
    )

    daily_performance[
        "Daily_IC_Winner"
    ] = np.select(
        [
            daily_performance[
                "IC_Difference_XGB_Minus_OLS"
            ].gt(
                0
            ),
            daily_performance[
                "IC_Difference_XGB_Minus_OLS"
            ].lt(
                0
            ),
        ],
        [
            "XGBoost",
            "Pooled OLS",
        ],
        default="Tie",
    )

    return daily_performance


