# 7. NEWEY-WEST INFERENCE
# ============================================================

def calculate_automatic_newey_west_lag(
    number_of_dates: int,
) -> int:
    """
    Calculate a sample-size-based Newey-West maximum lag:

        floor[4(T/100)^(2/9)]
    """

    if number_of_dates < 2:
        raise ValueError(
            "At least two daily observations are required "
            "for Newey-West inference."
        )

    lag = int(
        np.floor(
            4.0
            * (
                number_of_dates
                / 100.0
            )
            ** (
                2.0
                / 9.0
            )
        )
    )

    return max(
        1,
        min(
            lag,
            number_of_dates - 1,
        ),
    )


def perform_newey_west_ic_test(
    ic_differences: pd.Series,
) -> pd.DataFrame:
    """
    Test whether XGBoost produced a higher mean daily IC than OLS.

    Difference:
        d_t = IC_XGB,t - IC_OLS,t

    Directional hypotheses:
        H0: E[d_t] <= 0
        H1: E[d_t] > 0
    """

    values = ic_differences.dropna().to_numpy(
        dtype=float
    )

    if len(
        values
    ) < 2:
        raise ValueError(
            "The paired daily IC-difference series contains "
            "too few observations."
        )

    if not np.isfinite(
        values
    ).all():
        raise ValueError(
            "The paired daily IC-difference series contains "
            "non-finite values."
        )

    maximum_lag = calculate_automatic_newey_west_lag(
        len(
            values
        )
    )

    intercept = np.ones(
        (
            len(
                values
            ),
            1,
        )
    )

    fitted_model = sm.OLS(
        values,
        intercept,
    ).fit(
        cov_type="HAC",
        cov_kwds={
            "maxlags": maximum_lag,
            "use_correction": True,
        },
    )

    mean_difference = float(
        fitted_model.params[
            0
        ]
    )

    newey_west_standard_error = float(
        fitted_model.bse[
            0
        ]
    )

    if (
        not np.isfinite(
            newey_west_standard_error
        )
        or newey_west_standard_error <= 0
    ):
        raise ValueError(
            "The Newey-West standard error is invalid."
        )

    test_statistic = (
        mean_difference
        / newey_west_standard_error
    )

    one_sided_p_value = float(
        norm.sf(
            test_statistic
        )
    )

    two_sided_p_value = float(
        2.0
        * norm.sf(
            abs(
                test_statistic
            )
        )
    )

    critical_value = float(
        norm.ppf(
            1.0
            - SIGNIFICANCE_LEVEL
            / 2.0
        )
    )

    confidence_interval_lower = (
        mean_difference
        - critical_value
        * newey_west_standard_error
    )

    confidence_interval_upper = (
        mean_difference
        + critical_value
        * newey_west_standard_error
    )

    if (
        mean_difference > 0
        and one_sided_p_value
        < SIGNIFICANCE_LEVEL
    ):
        directional_decision = (
            "Reject H0: evidence that XGBoost had superior "
            "mean daily IC"
        )

    else:
        directional_decision = (
            "Fail to reject H0: no evidence that XGBoost had "
            "superior mean daily IC"
        )

    if (
        two_sided_p_value
        < SIGNIFICANCE_LEVEL
        and confidence_interval_upper < 0
    ):
        two_sided_interpretation = (
            "Statistically significant difference favouring "
            "Pooled OLS"
        )

    elif (
        two_sided_p_value
        < SIGNIFICANCE_LEVEL
        and confidence_interval_lower > 0
    ):
        two_sided_interpretation = (
            "Statistically significant difference favouring "
            "XGBoost"
        )

    else:
        two_sided_interpretation = (
            "No statistically significant two-sided difference"
        )

    return pd.DataFrame(
        [
            {
                "Difference_Definition": (
                    "XGBoost daily IC minus Pooled OLS daily IC"
                ),
                "Null_Hypothesis": (
                    "Mean paired daily IC difference was "
                    "less than or equal to zero"
                ),
                "Alternative_Hypothesis": (
                    "Mean paired daily IC difference was "
                    "greater than zero"
                ),
                "Daily_Observations": len(
                    values
                ),
                "Newey_West_Max_Lag": maximum_lag,
                "Mean_IC_Difference_XGB_Minus_OLS": (
                    mean_difference
                ),
                "Newey_West_Standard_Error": (
                    newey_west_standard_error
                ),
                "Normal_Test_Statistic": (
                    test_statistic
                ),
                "One_Sided_P_Value_XGB_Superior": (
                    one_sided_p_value
                ),
                "Two_Sided_P_Value": (
                    two_sided_p_value
                ),
                "Confidence_Level": (
                    1.0
                    - SIGNIFICANCE_LEVEL
                ),
                "Confidence_Interval_Lower": (
                    confidence_interval_lower
                ),
                "Confidence_Interval_Upper": (
                    confidence_interval_upper
                ),
                "Directional_Decision_At_5_Percent": (
                    directional_decision
                ),
                "Two_Sided_Interpretation_At_5_Percent": (
                    two_sided_interpretation
                ),
            }
        ]
    )


